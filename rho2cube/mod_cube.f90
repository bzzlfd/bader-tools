! ------------------------------------------------------------------
! mod_cube: writer for the Gaussian cube format (see the "Output
! File Formats" section of the cubegen documentation).
!
! Header layout:
!    line 1, 2      : comments
!    line 3         : natom  ox oy oz  nval    (I5,3F12.6,I5)
!                     nval = number of values per point (1 here)
!    lines 4-6      : n_i  v_ix v_iy v_iz  (I5,3F12.6), v_i = a_i/n_i
!    natom lines    : Z  charge  x y z     (I5,F12.6,3F12.6)
!    grid data      : (6E13.5); the grid is stored as N1*N2 records
!                     of length N3*NVal each, one write per record,
!                     third index fastest
!
! All values are in atomic units: bohr for lengths (a positive natom
! selects bohr); the density keeps its native unit.
! ------------------------------------------------------------------
module cube_mod
   use utils_mod
   use pwmat_io_mod, only: atom_config_t, rho_meta_t
   implicit none
   private
   public :: write_cube

contains

   subroutine write_cube(filename, atoms, meta, rho, comment2)
      character(*), intent(in) :: filename, comment2
      type(atom_config_t), intent(in) :: atoms
      type(rho_meta_t), intent(in) :: meta
      real(dp), intent(in) :: rho(:)
      integer :: u, i, j, k, ios
      real(dp) :: voxel(3), r(3)
      open(newunit=u, file=filename, status='replace', action='write', &
           iostat=ios)
      if (ios /= 0) call die('cannot open output file '//trim(filename))
      write(u, '(a)') 'Gaussian cube file, generated by convert_rho2cube.x'
      write(u, '(a)') trim(comment2)
      write(u, '(I5,3F12.6,I5)') atoms%natom, 0.0_dp, 0.0_dp, 0.0_dp, 1
      do i = 1, 3
         voxel = meta%AL(:,i) / real(meta%n(i), dp) / bohr_ang
         write(u, '(I5,3F12.6)') meta%n(i), voxel
      end do
      do i = 1, atoms%natom
         r = matmul(meta%AL, atoms%xfrac(i,:)) / bohr_ang
         write(u, '(I5,F12.6,3F12.6)') atoms%itype(i), 0.0_dp, r
      end do
      do i = 1, meta%n(1)
         do j = 1, meta%n(2)
            write(u, '(6E13.5)') &
               (rho((i-1)*meta%n(2)*meta%n(3) + (j-1)*meta%n(3) + k), k = 1, meta%n(3))
         end do
      end do
      close(u)
   end subroutine write_cube

end module cube_mod
